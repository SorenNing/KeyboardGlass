"""Deterministic, build-time PNG; never called from the keyboard process."""
from pathlib import Path
from PIL import Image
import base64, math
P=Path(__file__).resolve().parent
N=192
SCALE=3
RADIUS=16*SCALE
BORDER=3*SCALE
im=Image.new('RGBA',(N,N))
# Analytic rounded-box distance, four samples per output pixel.
for y in range(N):
    for x in range(N):
        samples=[]
        for sy,sx in [(0.25,0.25),(0.25,0.75),(0.75,0.25),(0.75,0.75)]:
            qx=abs(x+sx-N/2)-(N/2-RADIUS)
            qy=abs(y+sy-N/2)-(N/2-RADIUS)
            sdf=math.hypot(max(qx,0),max(qy,0))+min(max(qx,qy),0)-RADIUS
            if sdf>0: samples.append(0); continue
            depth=-sdf
            # Fixed glass body (15/255), a broad 3pt rim and a crisp outer
            # highlight. No gradient discontinuity between top and bottom.
            strength=0.75+0.25*(1-(y+sy)/N)
            band=max(0,1-depth/BORDER)
            highlight=math.exp(-((depth-1.1)/1.15)**2)
            samples.append(min(255,15+strength*(100*band+55*highlight)))
        alpha=round(sum(samples)/4)
        im.putpixel((x,y),(255,255,255,alpha) if alpha else (0,0,0,0))
im.save(P/'GlassBackground.png',compress_level=9)
data=base64.b64encode((P/'GlassBackground.png').read_bytes()).decode()
(P/'Material.h').write_text('// Generated by generate_material.py; fixed PNG at 3x.\nstatic NSString *const NGMaterialBase64 = @"'+data+'";\n')
if __name__=='__main__': print('192x192 RGBA; 16pt corners; 3pt rim; center alpha 15')
